const catalogues: Record<Locale, Record<MessageKey, string>> = { en, fa }

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string

export function translator(locale: Locale): Translate {
  const numbers = new Intl.NumberFormat(locale === 'fa' ? 'fa-IR' : 'en-US')
  return (key, values) => catalogues[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values?.[name]
    if (value === undefined) return match
    return typeof value === 'number' ? numbers.format(value) : value
  })
}

const storageKey = 'swarmops-cloud-locale'

/** The language a visitor chose before, or the one their browser prefers. */
export function initialLocale(): Locale {
  try {
    const saved = window.localStorage.getItem(storageKey)
    if (saved === 'en' || saved === 'fa') return saved
  } catch {
    // Storage can be unavailable in a private window; the browser's language
    // is then the best guess.
  }
  return navigator.language.toLowerCase().startsWith('fa') ? 'fa' : 'en'
}

export function rememberLocale(locale: Locale) {
  try {
    window.localStorage.setItem(storageKey, locale)
  } catch {
    // Not remembering a language is harmless.
  }
}
